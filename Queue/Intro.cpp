// Queue is a linear data structure that follows the First In First Out (FIFO) principle.
// In a queue, elements are added at the rear (enqueue) and removed from the front (dequeue).
// The main operations of a queue are:
// 1. Enqueue: Add an element to the rear of the queue.
// 2. Dequeue: Remove an element from the front of the queue.
// Queues can be implemented using arrays, linked lists, or other data structures.
// Common applications of queues include:
// - Task scheduling
// - Breadth-First Search (BFS) in graph algorithms
// In C++, the Standard Template Library (STL) provides a built-in queue class that can be used to implement queues easily.